import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useRef,
  useState,
} from "react";
import type { ReactNode } from "react";
import {
  AlertTriangle,
  CheckCircle2,
  Info,
  X,
  XCircle,
} from "lucide-react";

import { useLanguage } from "../i18n/LanguageContext";
import "./ToastStack.css";

type ToastKind = "success" | "info" | "warning" | "error";

type Toast = {
  id: number;
  kind: ToastKind;
  message: string;
};

type ToastAPI = {
  notify: (message: string, kind?: ToastKind) => void;
};

const ToastContext = createContext<ToastAPI | null>(null);
const MAX_VISIBLE = 3;
const DURATION_MS = 4500;

const icons = {
  success: CheckCircle2,
  info: Info,
  warning: AlertTriangle,
  error: XCircle,
};

/** Adapted from Bencho's ToastStack interaction, not its fixed demo pool.
 *  Notifications are generated by actual Chops actions, never invented events.
 *  A small capped stack replaces hover-only fan-out for touch accessibility.
 */
export function ToastProvider({ children }: { children: ReactNode }) {
  const { t } = useLanguage();
  const [toasts, setToasts] = useState<Toast[]>([]);
  const sequence = useRef(0);

  const dismiss = useCallback((id: number) => {
    setToasts((current) => current.filter((toast) => toast.id !== id));
  }, []);

  const notify = useCallback<ToastAPI["notify"]>((message, kind = "info") => {
    const toast: Toast = {
      id: ++sequence.current,
      kind,
      message,
    };
    setToasts((current) => [...current, toast].slice(-MAX_VISIBLE));
  }, []);

  // Each toast expires independently; all timeouts are cancelled on update.
  useEffect(() => {
    if (toasts.length === 0) return;
    const timers = toasts.map((toast) =>
      window.setTimeout(() => dismiss(toast.id), DURATION_MS),
    );
    return () => timers.forEach(window.clearTimeout);
  }, [toasts, dismiss]);

  return (
    <ToastContext.Provider value={{ notify }}>
      {children}
      <div className="chops-toasts" aria-label={t("Notifications")}>
        {toasts.map((toast) => {
          const Icon = icons[toast.kind];
          return (
            <div
              className="chops-toast"
              data-kind={toast.kind}
              role={toast.kind === "error" ? "alert" : "status"}
              key={toast.id}
            >
              <Icon size={18} strokeWidth={1.9} aria-hidden="true" />
              <span>{toast.message}</span>
              <button
                type="button"
                aria-label={t("Dismiss notification")}
                onClick={() => dismiss(toast.id)}
              >
                <X size={15} aria-hidden="true" />
              </button>
            </div>
          );
        })}
      </div>
    </ToastContext.Provider>
  );
}

export function useToast() {
  const context = useContext(ToastContext);
  if (!context) throw new Error("Missing ToastProvider");
  return context;
}
